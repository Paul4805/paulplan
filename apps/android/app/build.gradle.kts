// Tokens.kt is generated by `pnpm tokens` at the repo root and is gitignored.
// Fail with an instruction instead of a wall of unresolved-reference errors.
val generatedTokens = layout.projectDirectory.file(
    "src/main/java/com/slot/app/core/design/Tokens.kt",
)

val checkGeneratedTokens by tasks.registering {
    doFirst {
        if (!generatedTokens.asFile.exists()) {
            throw GradleException(
                "Design tokens are missing. Run `pnpm tokens` at the repository root, then sync again.",
            )
        }
    }
}

tasks.named("preBuild") {
    dependsOn(checkGeneratedTokens)
}

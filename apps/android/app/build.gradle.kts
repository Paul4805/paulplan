// Firebase config is injected at build time instead of shipping
// google-services.json: no plugin, no kept secret, one less file to forget.
// Put these in apps/android/local.properties (gitignored):
//   firebase.apiKey, firebase.applicationId, firebase.projectId,
//   firebase.storageBucket, firebase.senderId, google.webClientId
val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

fun localProperty(key: String): String = localProperties.getProperty(key, "")

